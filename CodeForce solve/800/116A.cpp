/*
Linear Kingdom-এ একটা ট্রাম লাইন আছে। ট্রামটা n টা স্টপে দাঁড়ায়, একের পর এক সিরিয়াল অনুযায়ী।

প্রতিটা স্টপে:
	•	কিছু লোক নেমে যায় → a[i]
	•	তারপর কিছু লোক উঠে → b[i]

প্রথম স্টপে ট্রাম একেবারে ফাঁকা (একজনও নেই)।
শেষ স্টপে ট্রামে থাকা সবাই নেমে যায়, কেউ আর উঠে না।

⸻

🧠 টাস্ক কী?

তুইকে বের করতে হবে:

🔍 ট্রামে সব সময় যত বেশি সংখ্যক লোক ছিল, সেই সংখ্যাটা —
মানে সর্বোচ্চ কতজন ট্রামে একসাথে ছিল — সেটাই হচ্ছে মিনিমাম ক্যাপাসিটি যেটা ট্রামে থাকা উচিত।

⸻

🔢 ইনপুট:

১. প্রথম লাইন: n → মোট কয়টা স্টপ
২. পরবর্তী n লাইনে:
প্রতিটা লাইনে থাকবে a[i] b[i]
	•	a[i]: কতজন নামল
	•	b[i]: কতজন উঠল

শর্ত:
	•	প্রথম স্টপে কেউ নামবে না → a[1] = 0
	•	শেষ স্টপে কেউ উঠবে না → b[n] = 0
	•	কাউকে নামানোর আগেই সে ট্রামে ছিল, তাই a[i] <= current_passengers
    
    Input:
4
0 3
2 5
4 2
4 0

স্টপ ধরে ধরে দেখি:
	•	স্টপ 1: 0 নামল, 3 উঠল → এখন আছে 3 জন
	•	স্টপ 2: 2 নামল (৩ - ২ = ১), ৫ উঠল → এখন আছে ১ + ৫ = ৬
	•	স্টপ 3: ৪ নামল (৬ - ৪ = ২), ২ উঠল → এখন আছে ২ + ২ = ৪
	•	স্টপ 4: ৪ নামল → ফাঁকা

📊 সবচেয়ে বেশি লোক ছিল ৬ জন।
✅ উত্তর: 6

*/
#include<iostream>
#include <algorithm>
using namespace std;
int main(){
    int n;
    cin>>n;
    int a[n];
    int b[n];
    int c[n];
    int cp=0;
    for (int i = 0; i < n; i++)
    {
        cin>>a[i]>>b[i];
        cp=(cp+b[i])-a[i];
        c[i]=cp;
        
    }
    int max_val = *max_element(c, c + n); //1st and last pointer in a array
    cout<<max_val;
    return 0;

}