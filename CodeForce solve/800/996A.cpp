#include <iostream>
#include <string>
#include <vector>
#include <algorithm>
using namespace std;

int main()
{
    int a[] = {100, 20, 10, 5, 1};
    int n;
    cin >> n;
    int c = 0;

    for (int i = 0; i < 5;)
    {
        if (n >= a[i])
        {
            n = n - a[i];
            c++;
        }

        else
        {
            i++;
        }
    }

    cout << c;

    return 0;
}

